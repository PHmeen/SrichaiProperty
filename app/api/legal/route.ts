export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const type = searchParams.get("type") || "all";

    // ดึงค่าจากตาราง system_configs ใน DB จริง
    const configs = await db.system_configs.findMany({
      where: {
        key: { in: ["privacy_policy", "terms_and_conditions"] }
      }
    });

    const configMap = new Map(configs.map(c => [c.key, c.value]));

    const privacyPolicy = configMap.get("privacy_policy") || DEFAULT_PRIVACY_POLICY;
    const terms = configMap.get("terms_and_conditions") || DEFAULT_TERMS;

    if (type === "privacy") return NextResponse.json({ success: true, content: privacyPolicy });
    if (type === "terms") return NextResponse.json({ success: true, content: terms });

    return NextResponse.json({
      success: true,
      privacyPolicy,
      terms
    });
  } catch {
    return NextResponse.json({
      success: true,
      privacyPolicy: DEFAULT_PRIVACY_POLICY,
      terms: DEFAULT_TERMS
    });
  }
}
